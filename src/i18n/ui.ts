/** Path of the same page in a given language: '/work/x/' ↔ '/it/work/x/' */
export function localePath(lang: Lang, path: string) {
  const clean = path.replace(/^\/it(?=\/|$)/, '') || '/';
  return lang === 'it' ? `/it${clean === '/' ? '/' : clean}` : clean;
}

